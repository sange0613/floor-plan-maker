// Run against an existing server. Playwright may be provided by the host runtime.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5188/')
  assert.match(await page.title(), /平面图制作/)
  assert.equal(await page.locator('.material-inspector').isVisible(), false, 'inspector starts folded')
  assert.equal(await page.getByRole('group', { name: '快捷黑白灰' }).getByRole('button').count(), 7)
  assert.ok((await page.locator('.preview-pane').boundingBox()).width > 1300, 'canvas uses the released sidebar space')
  const save = async () => {
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: '保存项目', exact: true }).click()
    const download = await pending
    return JSON.parse(await readFile(await download.path(), 'utf8'))
  }
  const live = data => Object.entries(data.editor.materialState.materials)
    .filter(([id]) => data.editor.materialState.assignments.some(([value]) => value === Number(id))).map(([, material]) => material)
  const image = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 200; c.height = 120
    const ctx = c.getContext('2d'); ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 200, 120)
    ctx.strokeStyle = 'black'; ctx.lineWidth = 2; ctx.strokeRect(10, 10, 180, 100)
    ctx.beginPath(); ctx.moveTo(100, 10); ctx.lineTo(100, 110); ctx.stroke()
    return c.toDataURL()
  })
  await page.locator('input[type=file]').first().setInputFiles({ name: 'rooms.png', mimeType: 'image/png', buffer: Buffer.from(image.split(',')[1], 'base64') })
  await page.waitForFunction(() => document.querySelector('.region-status')?.textContent.includes('2 个区域'))
  const canvas = page.getByLabel('线稿填色画布')
  const box = await canvas.boundingBox()
  await canvas.click({ position: { x: box.width * .25, y: box.height * .5 } })
  await page.getByRole('button', { name: '45°剖面线', exact: true }).click()
  await canvas.click({ position: { x: box.width * .75, y: box.height * .5 } })
  assert.equal(await page.locator('.material-inspector').isVisible(), false, 'continuous fill never opens inspector')
  const filled = await save()
  const toast = await page.getByRole('status').boundingBox()
  const toolbar = await page.locator('.canvas-floating-controls').boundingBox()
  assert.ok(toast.y >= toolbar.y + toolbar.height, 'status messages do not cover canvas controls')
  assert.deepEqual(live(filled).map(m => m.type), ['solid', 'hatch'])
  assert.ok(live(filled).every(m => m.shadow.angle === 33 && m.shadow.opacity === 44))
  await page.getByRole('button', { name: '选择中灰 #888888', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '45°剖面线', exact: true }).getAttribute('aria-pressed'), 'true', 'changing color preserves the chosen fill mode')
  await page.getByRole('button', { name: '阴影选项', exact: true }).click()
  assert.ok(await page.getByRole('dialog', { name: '阴影选项' }).isVisible())
  assert.equal(await page.getByLabel('阴影调整范围').inputValue(), 'color')
  await page.locator('input[id^="shadow-angle-"]').fill('70')
  await page.locator('input[id^="shadow-angle-"]').press('Tab')
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog', { name: '阴影选项' }).count(), 0)
  assert.ok(live(await save()).every(m => m.shadow.angle === 70))
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  assert.ok(live(await save()).every(m => m.shadow.angle === 33))
  for (const steps of ['23', '25']) {
    await page.getByRole('button', { name: '阴影选项', exact: true }).click()
    await page.getByRole('dialog', { name: '阴影选项' }).locator('input[type=number]').first().fill(steps)
    await page.locator('.region-status').click()
  }
  assert.ok(live(await save()).every(m => m.shadow.steps === 25))
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  assert.ok(live(await save()).every(m => m.shadow.steps === 23), 'outside-dismissed number edits remain separate undo entries')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  assert.ok(live(await save()).every(m => m.shadow.steps === 20))
  await page.getByRole('button', { name: '属性与图层', exact: true }).click()
  assert.ok(await page.locator('.material-inspector').isVisible())
  await page.getByRole('tab', { name: '图层', exact: true }).click()
  await page.getByRole('button', { name: '隐藏材质图层 45°剖面线', exact: true }).click()
  assert.equal(live(await save()).find(m => m.type === 'hatch').visible, false)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('button', { name: '收起属性面板', exact: true }).click()
  await page.getByRole('button', { name: '画布工具', exact: true }).click()
  await page.getByRole('button', { name: '向右旋转90度', exact: true }).click()
  const rotated = await save(); assert.equal(rotated.editor.width, filled.editor.height)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  const restored = await save(); assert.deepEqual(restored.editor.materialState, filled.editor.materialState)
  await page.getByRole('button', { name: '画布工具', exact: true }).click()
  await page.getByRole('button', { name: '自由裁剪', exact: true }).click()
  await page.getByRole('button', { name: '应用裁剪', exact: true }).click()
  const cropped = await save()
  assert.ok(cropped.editor.width < filled.editor.width && cropped.editor.height < filled.editor.height)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  assert.deepEqual((await save()).editor.materialState, filled.editor.materialState, 'crop can restore all fill assignments')
  const pngPending = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出作品', exact: true }).click()
  const png = await readFile(await (await pngPending).path())
  assert.equal(png.subarray(1, 4).toString(), 'PNG')
  assert.equal(png.readUInt32BE(16), filled.editor.width)
  assert.equal(png.readUInt32BE(20), filled.editor.height)
  await page.getByRole('button', { name: '更多操作', exact: true }).click()
  assert.ok(await page.getByRole('button', { name: '打开项目', exact: true }).isVisible())
  await page.getByRole('button', { name: '画面与画布设置', exact: true }).click()
  assert.ok(await page.getByRole('dialog', { name: '画面与画布设置面板' }).isVisible())
  assert.ok(await page.getByRole('button', { name: '保存项目', exact: true }).evaluate(button => {
    const bounds = button.getBoundingClientRect()
    return !!document.elementFromPoint(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)?.closest('.settings-backdrop')
  }), 'settings backdrop blocks header commands while the modal is open')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '更多配色', exact: true }).click()
  await page.getByLabel('选择配色方案').selectOption('bauhaus-classic')
  await page.getByRole('button', { name: '保存项目', exact: true }).focus()
  assert.equal(await page.getByLabel('选择配色方案').count(), 0, 'keyboard focus leaving a panel dismisses it')
  await page.getByRole('button', { name: '更多配色', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByLabel('选择配色方案').count(), 0)
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'rooms.weicolor', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(filled)) })
  await page.waitForFunction(() => document.querySelector('[role=status]')?.textContent.includes('项目已打开'))
  assert.deepEqual(live(await save()), live(filled))
  if (process.env.QA_DIR) await page.screenshot({ path: `${process.env.QA_DIR}/workbench-desktop.png` })
  for (const [width, height] of [[1024, 768], [390, 844], [320, 667]]) {
    await page.setViewportSize({ width, height })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    for (const name of ['保存项目', '更多操作', '阴影选项', '45°剖面线', '画布工具', '属性与图层']) {
      const bounds = await page.getByRole('button', { name, exact: true }).boundingBox()
      assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y + bounds.height <= height, `${name} is reachable at ${width}`)
    }
    await page.getByRole('button', { name: '阴影选项', exact: true }).click()
    const popup = await page.getByRole('dialog', { name: '阴影选项' }).boundingBox()
    assert.ok(popup.x >= 0 && popup.x + popup.width <= width && popup.y + popup.height <= height)
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '属性与图层', exact: true }).click()
    assert.ok(await page.getByRole('tab', { name: '属性', exact: true }).isVisible())
    await page.keyboard.press('Escape')
    for (const name of ['更多操作', '画布工具', '更多配色']) {
      await page.getByRole('button', { name, exact: true }).click()
      const bounds = await page.getByRole('dialog', { name, exact: true }).boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y + bounds.height <= height, `${name} popup stays in view at ${width}`)
      await page.keyboard.press('Escape')
    }
    assert.equal(await page.locator('.material-inspector').isVisible(), false)
    if (process.env.QA_DIR && width === 390) await page.screenshot({ path: `${process.env.QA_DIR}/workbench-mobile.png` })
  }
  assert.equal(await page.locator('vite-error-overlay').count(), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: compact workbench, continuous fill, batch shadows/undo, layers, rotation/crop, PNG export, save/reopen, modal stacking, menus/Escape, responsive viewports')
} finally {
  await browser.close()
}
