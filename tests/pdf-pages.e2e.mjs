import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.setContent('<style>@page{size:200px 120px;margin:0}body{margin:0}.sheet{height:120px;break-after:page} .box{position:relative;top:10px;margin:auto;width:150px;height:90px;border:2px solid black}</style><div class="sheet"><div class="box"></div></div><div class="sheet"><div class="box"></div></div>')
  const pdf = await page.pdf({ printBackground: true, preferCSSPageSize: true })
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5188/')
  await page.getByRole('button', { name: '修改左上角名称' }).click()
  await page.getByLabel('自定义左上角名称').fill('我的设计工作室')
  await page.getByLabel('自定义左上角名称').press('Enter')
  await page.reload()
  assert.equal(await page.getByRole('button', { name: '修改左上角名称' }).textContent(), '我的设计工作室')
  await page.getByRole('button', { name: '更多操作' }).click()
  await page.getByRole('button', { name: '区域识别', exact: true }).click()
  const recognition = page.getByRole('dialog', { name: '区域识别' })
  assert.ok(await recognition.isVisible())
  await recognition.getByRole('button', { name: /较强/ }).click()
  assert.equal(await recognition.getByRole('button', { name: /较强/ }).getAttribute('aria-pressed'), 'true')
  await recognition.getByRole('button', { name: /轻度/ }).click()
  await recognition.getByRole('button', { name: '关闭区域识别' }).click()
  await page.locator('input[type=file]').first().setInputFiles({ name: 'two-pages.pdf', mimeType: 'application/pdf', buffer: pdf })
  const pages = page.getByLabel('PDF 分页')
  await pages.getByText('第 1 / 2 页').waitFor()
  await page.waitForFunction(() => !document.querySelector('.active-tool-status')?.textContent.includes('处理中'))
  const canvas = page.getByLabel('线稿填色画布')
  await canvas.click()
  const save = async () => {
    const pending = page.waitForEvent('download')
    await page.getByRole('button', { name: '保存项目', exact: true }).click()
    return JSON.parse(await readFile(await (await pending).path(), 'utf8'))
  }
  const first = await save()
  assert.ok(first.editor.materialState.assignments.some(([value]) => value > 0))
  await page.getByRole('button', { name: '阴影选项' }).click()
  await page.getByLabel('投影角度数值').fill('-45')
  await page.getByLabel('投影角度数值').press('Tab')
  assert.ok(Object.values((await save()).editor.materialState.materials).some(material => material.shadow?.angle === -45))
  await page.getByRole('button', { name: '阴影选项' }).click()
  const slider = page.getByLabel('总距离滑杆')
  const sliderBox = await slider.boundingBox()
  await page.mouse.move(sliderBox.x + sliderBox.width * .07, sliderBox.y + sliderBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(sliderBox.x + sliderBox.width * .4, sliderBox.y + sliderBox.height / 2, { steps: 8 })
  await page.mouse.up()
  const distance = Number(await page.getByLabel('总距离数值').inputValue())
  assert.ok(sliderBox.width > 180, 'shadow slider spans the panel')
  assert.ok(distance > 150 && distance < 250, `drag updated distance: ${distance}`)
  await page.keyboard.press('Escape')
  assert.ok(Object.values((await save()).editor.materialState.materials).some(material => material.shadow?.distance === distance))
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await pages.getByRole('button', { name: '下一页' }).click()
  await pages.getByText('第 2 / 2 页').waitFor()
  await page.waitForFunction(() => !document.querySelector('.active-tool-status')?.textContent.includes('处理中'))
  await page.getByRole('button', { name: '选择黑 #000000', exact: true }).click()
  await canvas.click()
  const second = await save()
  assert.ok(second.editor.materialState.assignments.some(([value]) => value > 0))
  await pages.getByRole('button', { name: '上一页' }).click()
  await pages.getByText('第 1 / 2 页').waitFor()
  assert.deepEqual((await save()).editor.materialState, first.editor.materialState)
  const downloadPending = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出作品', exact: true }).click()
  assert.match((await downloadPending).suggestedFilename(), /第1页/)
  await page.locator('input[type=file]').nth(1).setInputFiles({ name: 'saved.weicolor', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(second)) })
  await pages.getByText('第 2 / 2 页').waitFor()
  assert.deepEqual((await save()).editor.materialState, second.editor.materialState)
  await pages.getByRole('button', { name: '上一页' }).click()
  await pages.getByText('第 1 / 2 页').waitFor()
  assert.deepEqual((await save()).editor.materialState, first.editor.materialState)
  console.log('PASS: two PDF pages retain fill, export page number, and reopen project')
} finally { await browser.close() }
